import fs from 'node:fs';

const source = new URL('../emba/november-facts-videos.json', import.meta.url);
const target = new URL('../functions/_shared/november-facts-videos.js', import.meta.url);
const manifest = JSON.parse(fs.readFileSync(source, 'utf8'));
const generated = '// Generated by scripts/generate-emba-november-facts-videos.mjs. Edit the canonical JSON, then regenerate.\n'
  + `export default ${JSON.stringify(manifest, null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
    throw new Error('Facts video companion is stale. Run node scripts/generate-emba-november-facts-videos.mjs');
  }
  console.log('Facts video companion matches canonical JSON.');
} else {
  fs.writeFileSync(target, generated);
  console.log('Generated functions/_shared/november-facts-videos.js from canonical JSON.');
}
