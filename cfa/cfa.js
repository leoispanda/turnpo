  if (item?.type === "monthly_index") return "Open Reading Checklist →";
  if (item?.type === "study_guide") return "Open Study Card →";
  if (item?.type === "case_study") return "Open Case Card →";
  if (item?.type === "source_pdf") return "Open Source PDF →";
